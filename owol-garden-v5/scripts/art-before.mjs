import { chromium } from 'playwright-core';
import fs from 'node:fs/promises';
import { artScene } from '../src/art-scene.js';
const {config,items}=artScene();
const fixture={version:3,sceneConfig:config,items,pending:[],profile:{space:'주택 앞마당',size:'6 × 4.5 m',sun:'모르겠어요',mood:'고요하게 머물도록'},wish:'',camera:{position:[5.46,5.7,6.78],target:[0,.65,0],view:'edit'}};
await fs.writeFile('evidence/art-fixture.json',JSON.stringify(fixture,null,2));
const b=await chromium.launch({executablePath:'/usr/bin/chromium',args:['--no-sandbox','--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader']});
const p=await b.newPage({viewport:{width:1440,height:960},deviceScaleFactor:1});p.setDefaultTimeout(120000);
const errors=[];p.on('pageerror',e=>errors.push(e.message));p.on('console',m=>{if(m.type()==='error')errors.push(m.text())});
await p.goto('http://127.0.0.1:5176');await p.waitForFunction(()=>window.owol);
await p.locator('#import-open').click();await p.locator('#import-file').setInputFiles({name:'art-fixture.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(fixture))});
await p.waitForFunction(()=>!owol.stats().camera.running);
await p.screenshot({path:'evidence/before-ui.png'});
const d=p.waitForEvent('download');await p.locator('#scene-png').click();await(await d).saveAs('evidence/before-scene.png');
await fs.writeFile('evidence/before-state.json',JSON.stringify(await p.evaluate(()=>({state:owol.state(),stats:owol.stats()})),null,2));
await fs.writeFile('evidence/before-errors.json',JSON.stringify(errors));
console.log({items:items.length,errors});await b.close();
